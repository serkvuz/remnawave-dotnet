// Generates `UnwrapAsync()` extension methods for every Remnawave response envelope.
//
// Usage: dotnet run scripts/GenerateExtensions.cs -- <generated-models-dir> <output.cs>
//
// Every Remnawave endpoint wraps its payload in `{ "response": ... }`. Kiota models this faithfully
// (e.g. UserResponseDto.Response : User). This script scans the Kiota output and emits one strongly
// typed extension per envelope so callers can write:
//
//     User user = await client.Api.Users[uuid].GetAsync().UnwrapAsync();

#:property PublishAot=false
#:property ImplicitUsings=enable
#:property TreatWarningsAsErrors=false

using System.Text;
using System.Text.RegularExpressions;

var modelsDir = args[0];
var output = args[1];

var classRegex = new Regex(@"public partial class (\w+)\s*:", RegexOptions.Compiled);
// Kiota emits a nullable variant under `#if NETSTANDARD2_1_OR_GREATER || NETCOREAPP3_1_OR_GREATER`; match that one.
var responseRegex = new Regex(@"public ((?:List<)?global::[\w.<>:, ]+?)\? Response \{ get; set; \}", RegexOptions.Compiled);

var envelopes = new List<(string Envelope, string Payload)>();
foreach (var file in Directory.EnumerateFiles(modelsDir, "*.cs").Order(StringComparer.Ordinal))
{
    var text = File.ReadAllText(file);
    var cls = classRegex.Match(text);
    var resp = responseRegex.Match(text);
    if (!cls.Success || !resp.Success) continue;
    envelopes.Add(($"global::Remnawave.Client.Models.{cls.Groups[1].Value}", resp.Groups[1].Value));
}

var sb = new StringBuilder();
sb.AppendLine("// <auto-generated>");
sb.AppendLine("// Generated by scripts/GenerateExtensions.cs from the Kiota models. Do not edit.");
sb.AppendLine("// </auto-generated>");
sb.AppendLine("#nullable enable");
sb.AppendLine("using System.Collections.Generic;");
sb.AppendLine("using System.Threading.Tasks;");
sb.AppendLine();
sb.AppendLine("namespace Remnawave.Client;");
sb.AppendLine();
sb.AppendLine("/// <summary>Unwraps the <c>{ \"response\": ... }</c> envelope returned by every Remnawave endpoint.</summary>");
sb.AppendLine("public static partial class RemnawaveResponseExtensions");
sb.AppendLine("{");
foreach (var (envelope, payload) in envelopes)
{
    var name = envelope[(envelope.LastIndexOf('.') + 1)..];
    sb.AppendLine($"    /// <summary>Awaits the request and returns <see cref=\"{envelope}.Response\"/>.</summary>");
    sb.AppendLine($"    /// <exception cref=\"global::Remnawave.Client.RemnawaveEmptyResponseException\">The panel returned no payload.</exception>");
    sb.AppendLine($"    public static async Task<{payload}> UnwrapAsync(this Task<{envelope}?> request)");
    sb.AppendLine($"        => (await request.ConfigureAwait(false))?.Response ?? throw new global::Remnawave.Client.RemnawaveEmptyResponseException(\"{name}\");");
    sb.AppendLine();
}
sb.AppendLine("}");

File.WriteAllText(output, sb.ToString());
Console.WriteLine($"Generated {envelopes.Count} UnwrapAsync() extensions -> {output}");
